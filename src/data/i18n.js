function isProtectedElement(element) {
  return element.closest('pre, code, svg, script, style, textarea, [contenteditable="true"]');
}

export function translateString(value, language = 'en') {
  if (language !== 'ar' || !value) return value;
  const match = value.match(/^(\s*)([\s\S]*?)(\s*)$/u);
  const core = match?.[2] ?? value;
  const translated = arabic[core];
  return translated ? `${match[1]}${translated}${match[3]}` : value;
}

function translateTextNode(node, language) {
  if (language !== 'ar' || !node.parentElement || isProtectedElement(node.parentElement)) return;
  const translated = translateString(node.nodeValue, language);
  if (translated !== node.nodeValue) node.nodeValue = translated;
}

function translateAttributes(element, language) {
  if (!(element instanceof Element) || isProtectedElement(element)) return;
  for (const attribute of ['aria-label', 'title', 'placeholder', 'alt']) {
    if (!element.hasAttribute(attribute)) continue;
    const original = element.getAttribute(attribute);
    const translated = translateString(original, language);
    if (translated !== original) element.setAttribute(attribute, translated);
  }
}

function visitNode(node, language) {
  if (node.nodeType === Node.TEXT_NODE) { translateTextNode(node, language); return; }
  if (!(node instanceof Element) || isProtectedElement(node)) return;
  translateAttributes(node, language);
  const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT);
  let textNode;
  while ((textNode = walker.nextNode())) translateTextNode(textNode, language);
  node.querySelectorAll('[aria-label], [title], [placeholder], [alt]').forEach((element) => translateAttributes(element, language));
}

export function applyLocalization(root, language) {
  visitNode(root, language);
}

export function observeLocalization(root, getLanguage) {
  const observer = new MutationObserver((records) => {
    const language = getLanguage();
    for (const record of records) {
      if (record.type === 'characterData') translateTextNode(record.target, language);
      if (record.type === 'attributes') translateAttributes(record.target, language);
      if (record.type === 'childList') record.addedNodes.forEach((node) => visitNode(node, language));
    }
  });
  observer.observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ['aria-label', 'title', 'placeholder', 'alt'] });
  return () => observer.disconnect();
}
